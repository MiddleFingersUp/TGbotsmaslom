"""Staff-reply processing: relay to client, /back return (Stage 7.2).

Implements docs/DEVELOPMENT_PLAN.md Stage 7 task 4 with the user-approved
PLAN-OD-5 mechanics (docs/ARCHITECTURE.md §13):

- the incoming message is a GROUP message already marked `is_staff_group`
  by the Telegram adapter;
- the tenant is resolved by `tenants.staff_chat_id == chat.id`
  (unknown chat → logged and silently ignored);
- ONLY replies to the handoff notification (`reply_to_message_id ==
  handoffs.staff_message_id`) with an ACTIVE handoff are processed;
  everything else in the group is silently ignored (warn-logged);
- messages from bots (`from.is_bot`) are always ignored (loop protection);
- "/back" (case-insensitive, trailing words allowed) →
  `handoffs.status=returned`, `returned_at=now`,
  `conversations.handoff_active=False`; the dialog state goes back to
  `need_discovery` (backend transition, ARCHITECTURE §13) + confirmation
  to the staff chat; no client message is sent;
- plain text → persisted as `Message(role=staff,
  telegram_message_id=group message id)` in the caller's transaction
  (the natural Telegram id makes retries idempotent — one row), then
  delivered to the client through the Caller-Bot
  (`customers.telegram_chat_id`) AFTER the commit; a delivery failure is
  logged and reported honestly in the outcome, never raised.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Literal
from uuid import UUID

from aiogram import Bot
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from src.db.models.conversations import Conversation
from src.db.models.customers import Customer
from src.db.models.enums import ConversationState, HandoffStatus, MessageRole
from src.db.models.handoffs import Handoff
from src.db.models.messages import Message
from src.db.models.tenants import Tenant
from src.monitoring.logging import get_logger
from src.telegram_adapter.schemas import IncomingMessage

logger = get_logger("handoff.use_case")

_BACK_PREFIX = "/back"
_HANDOFF_RETURNED_CONFIRMATION = "Диалог возвращён в AI-режим."
_DELIVERED_CONFIRMATION = "Отправлено клиенту."


@dataclass(frozen=True)
class StaffReplyOutcome:
    """Honest handling result (no PII, identifiers only)."""

    status: Literal["sent_to_client", "handoff_returned", "ignored", "delivery_failed"]
    reason: str


def _is_back_command(text: str | None) -> bool:
    """'/back' prefix, case-insensitive, trailing words allowed (PLAN-OD-5)."""
    if not text:
        return False
    stripped = text.strip().lower()
    return stripped == _BACK_PREFIX or stripped.startswith(_BACK_PREFIX + " ")


def _extract_reply_to(incoming: IncomingMessage) -> int | None:
    """Telegram id of the message being replied to (notification message)."""
    raw = incoming.raw_update or {}
    message = raw.get("message")
    if not isinstance(message, dict):
        return None
    reply = message.get("reply_to_message")
    if not isinstance(reply, dict):
        return None
    reply_id = reply.get("message_id")
    return int(reply_id) if isinstance(reply_id, int) else None


def _is_from_bot(incoming: IncomingMessage) -> bool:
    """Loop protection: group messages generated by bots are always ignored."""
    raw = incoming.raw_update or {}
    message = raw.get("message")
    if not isinstance(message, dict):
        return False
    sender = message.get("from")
    return bool(isinstance(sender, dict) and sender.get("is_bot"))


class ProcessStaffReplyUseCase:
    """Processes one staff-group update inside the caller's transaction."""

    def __init__(self, session: AsyncSession, bot: Bot | None = None) -> None:
        """`bot` is the Caller-Bot instance; None → fail-closed delivery."""
        self.session = session
        self.bot = bot

    async def execute(self, incoming: IncomingMessage) -> StaffReplyOutcome:
        """Route one staff-group update through the PLAN-OD-5 rules."""
        if not incoming.is_staff_group:
            return await self._ignore("not_staff_group")
        if _is_from_bot(incoming):
            logger.warning("staff_reply.bot_message_ignored", tenant_id=str(incoming.tenant_id))
            return StaffReplyOutcome(status="ignored", reason="bot_sender")

        text = (incoming.text or "").strip()
        if not text:
            return await self._ignore("empty_text")

        chat_id = incoming.user.telegram_chat_id
        tenant = await self._tenant_by_chat(chat_id)
        if tenant is None:
            logger.warning("staff_reply.unknown_chat", staff_chat_id=chat_id)
            return StaffReplyOutcome(status="ignored", reason="unknown_staff_chat")

        reply_to = _extract_reply_to(incoming)
        if reply_to is None:
            return await self._ignore("not_a_reply")

        handoff = await self._active_handoff_by_notification(incoming.tenant_id, reply_to)
        if handoff is None:
            return await self._ignore("no_active_handoff_for_notification")

        conversation = await self.session.get(Conversation, handoff.conversation_id)
        if conversation is None:
            logger.warning(
                "staff_reply.conversation_missing",
                tenant_id=str(incoming.tenant_id),
                conversation_id=str(handoff.conversation_id),
            )
            return StaffReplyOutcome(status="ignored", reason="conversation_missing")

        if _is_back_command(text):
            return await self._return_to_ai(handoff, conversation)

        return await self._relay_to_client(incoming, handoff, conversation, text)

    # ─── /back path ─────────────────────────────────────────────────────

    async def _return_to_ai(
        self, handoff: Handoff, conversation: Conversation
    ) -> StaffReplyOutcome:
        """PLAN-OD-5: returned → flag cleared, state back to need_discovery."""
        now = datetime.now(UTC)
        handoff.status = HandoffStatus.RETURNED
        handoff.returned_at = now
        conversation.handoff_active = False
        # Backend transition (ARCHITECTURE §13 handoff → AI resumed).
        conversation.state = ConversationState.NEED_DISCOVERY
        await self.session.commit()

        await self._notify_staff(
            tenant_chat=handoff.staff_chat_id, text=_HANDOFF_RETURNED_CONFIRMATION
        )
        logger.info(
            "staff_reply.handoff_returned",
            tenant_id=str(handoff.tenant_id),
            handoff_id=str(handoff.id),
        )
        return StaffReplyOutcome(status="handoff_returned", reason="back_command")

    # ─── relay path ─────────────────────────────────────────────────────

    async def _relay_to_client(
        self,
        incoming: IncomingMessage,
        handoff: Handoff,
        conversation: Conversation,
        text: str,
    ) -> StaffReplyOutcome:
        """Persist the staff answer (idempotent) then deliver to the client."""
        duplicate = await self._duplicate_message(incoming)
        if duplicate:
            return await self._ignore("duplicate_staff_message")

        customer = await self.session.get(Customer, conversation.customer_id)
        if customer is None or customer.telegram_chat_id is None:
            logger.warning(
                "staff_reply.customer_missing",
                tenant_id=str(handoff.tenant_id),
                conversation_id=str(conversation.id),
            )
            return StaffReplyOutcome(status="ignored", reason="customer_missing")

        self.session.add(
            Message(
                tenant_id=handoff.tenant_id,
                conversation_id=conversation.id,
                role=MessageRole.STAFF,
                text=text,
                telegram_message_id=incoming.telegram_message_id,
                created_at=datetime.now(UTC),
            )
        )
        conversation.message_count += 1
        conversation.last_message_at = datetime.now(UTC)
        await self.session.commit()  # persist first (fail-closed delivery contract)

        delivered = await self._deliver_to_client(customer.telegram_chat_id, text)
        if delivered:
            await self._notify_staff(handoff.staff_chat_id, _DELIVERED_CONFIRMATION)
            return StaffReplyOutcome(status="sent_to_client", reason="delivered")

        logger.warning(
            "staff_reply.delivery_failed",
            tenant_id=str(handoff.tenant_id),
            conversation_id=str(conversation.id),
        )
        return StaffReplyOutcome(status="delivery_failed", reason="client_delivery_failed")

    async def _duplicate_message(self, incoming: IncomingMessage) -> bool:
        """Natural Telegram id: a repeat staff update never duplicates a row."""
        query = select(Message).where(
            Message.tenant_id == incoming.tenant_id,
            Message.telegram_message_id == incoming.telegram_message_id,
        )
        result = await self.session.execute(query)
        return result.scalars().first() is not None

    async def _deliver_to_client(self, client_chat_id: int, text: str) -> bool:
        """Caller-Bot delivery; transport failures never raise (fail-closed)."""
        if self.bot is None:
            logger.warning("staff_reply.no_bot_instance")
            return False
        try:
            await self.bot.send_message(chat_id=client_chat_id, text=text)
            return True
        except Exception as error:  # noqa: BLE001 - fail-closed delivery
            logger.warning(
                "staff_reply.client_delivery_failed",
                error_type=type(error).__name__,
            )
            return False

    async def _notify_staff(self, tenant_chat: int, text: str) -> None:
        """Short confirmation to the staff group (never raises)."""
        if self.bot is None:
            return
        try:
            await self.bot.send_message(chat_id=tenant_chat, text=text)
        except Exception as error:  # noqa: BLE001 - confirmations are best-effort
            logger.warning("staff_reply.confirmation_failed", error_type=type(error).__name__)

    # ─── lookups ────────────────────────────────────────────────────────

    async def _tenant_by_chat(self, chat_id: int) -> Tenant | None:
        """Resolve the tenant configured with this internal chat/group."""
        query = select(Tenant).where(Tenant.staff_chat_id == chat_id)
        result = await self.session.execute(query)
        return result.scalars().first()

    async def _active_handoff_by_notification(
        self,
        tenant_id: UUID,
        staff_message_id: int,
    ) -> Handoff | None:
        """The ACTIVE handoff this notification belongs to (requires delivery)."""
        query = select(Handoff).where(
            Handoff.tenant_id == tenant_id,
            Handoff.staff_message_id == staff_message_id,
            Handoff.status == HandoffStatus.ACTIVE,
        )
        result = await self.session.execute(query)
        return result.scalars().first()

    async def _ignore(self, reason: str) -> StaffReplyOutcome:
        """Silent-ignore helper with a debug log (staff group is chatty)."""
        logger.debug("staff_reply.ignored", reason=reason)
        return StaffReplyOutcome(status="ignored", reason=reason)
